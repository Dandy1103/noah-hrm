CREATE TABLE IF NOT EXISTS attendance_records (
    attendance_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_number TEXT NOT NULL REFERENCES employees (employee_number),
    work_date DATE NOT NULL,
    clock_in TIME,
    clock_out TIME,
    note TEXT,
    CHECK (clock_in IS NOT NULL OR clock_out IS NOT NULL),
    CHECK (clock_in IS NULL OR clock_out IS NULL OR clock_out >= clock_in),
    CHECK (note IS NULL OR char_length(btrim(note)) BETWEEN 1 AND 200),
    UNIQUE (employee_number, work_date)
);

CREATE TABLE IF NOT EXISTS leave_records (
    leave_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_number TEXT NOT NULL REFERENCES employees (employee_number),
    leave_type TEXT NOT NULL CHECK (leave_type IN (
        'annual', 'sick', 'personal', 'menstrual', 'bereavement', 'marriage', 'official'
    )),
    starts_on DATE NOT NULL,
    ends_on DATE NOT NULL,
    note TEXT,
    CHECK (ends_on >= starts_on),
    CHECK (note IS NULL OR char_length(btrim(note)) BETWEEN 1 AND 200)
);

CREATE TABLE IF NOT EXISTS overtime_records (
    overtime_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_number TEXT NOT NULL REFERENCES employees (employee_number),
    work_date DATE NOT NULL,
    starts_at TIME NOT NULL,
    ends_at TIME NOT NULL,
    reason TEXT NOT NULL CHECK (char_length(btrim(reason)) BETWEEN 1 AND 200),
    CHECK (ends_at > starts_at)
);

CREATE TABLE IF NOT EXISTS trip_records (
    trip_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_number TEXT NOT NULL REFERENCES employees (employee_number),
    place TEXT NOT NULL CHECK (char_length(btrim(place)) BETWEEN 1 AND 100),
    starts_on DATE NOT NULL,
    ends_on DATE NOT NULL,
    reason TEXT NOT NULL CHECK (char_length(btrim(reason)) BETWEEN 1 AND 200),
    CHECK (ends_on >= starts_on)
);
